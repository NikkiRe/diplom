#!/usr/bin/env python3
"""Оценка бюджета API для плана экспериментов концепции evidence-first (расчёт, не измерение).

Цены: снимок RouterAI 06.10.2026 (`GET https://routerai.ru/api/v1/models`, поля pricing × 1e6 = ₽ за 1M),
совпадает с F_artifacts/routerai_models_2026-10-06.json и GAP1 §8.6.
Объёмы экспериментов и размеры промптов — ДОПУЩЕНИЯ концепции (помечены ниже), а не данные.
Верхняя граница считается БЕЗ кэша провайдера (консервативно); «реалистичная» — с долей кэша 50 %
(по модели GAP1 §6.2 для сценария «пользователь + датчики + heartbeat» доля кэша 50–71 %).

Запуск: python3 budget.py
"""
from math import sqrt

# ₽ за 1M токенов: вход, чтение кэша, выход (снимок RouterAI 06.10.2026)
PRICE = {
    "gpt-4.1-nano": (11.04, 2.76, 44.16),
    "gpt-4o-mini": (16.56, 8.28, 66.25),
    "gpt-4.1-mini": (44.16, 11.04, 176.66),
    "gpt-5-nano": (5.52, 0.55, 44.16),
    "gpt-5-mini": (27.60, 2.76, 220.82),
    "gpt-6-luna": (11.04, 1.10, 55.21),   # + запись кэша 13.80 (не учитывается в верхней границе без кэша)
}
REASONING = {"gpt-5-nano": 400, "gpt-5-mini": 400}  # ДОПУЩЕНИЕ: скрытые reasoning-токены на вызов (тарифицируются как выход)


def cost(model, n_calls, tok_in, tok_out, cache_share=0.0):
    p_in, p_cache, p_out = PRICE[model]
    out = tok_out + REASONING.get(model, 0)
    rub_in = n_calls * tok_in * ((1 - cache_share) * p_in + cache_share * p_cache) / 1e6
    rub_out = n_calls * out * p_out / 1e6
    return rub_in + rub_out, n_calls * tok_in, n_calls * out


rows = []

# E0. Калибровка TTL и полей usage: из GAP1_artifacts/ttl_probe_plan_stdout.txt (₽ на одного провайдера) × 2 провайдера
e0 = (6.09 + 8.98 + 2.98) * 2 + 2 * 4.0      # + gpt-4.1-nano ≈ 4 ₽ на провайдера (ДОПУЩЕНИЕ по аналогии с 4o-mini)
# + задержки из сети РФ: 4 модели × 144 коротких запроса/сут (раз в 10 мин) × 1 сут, 1 500 вх / 20 вых
for m in ("gpt-4.1-nano", "gpt-4o-mini", "gpt-5-mini", "gpt-6-luna"):
    e0 += cost(m, 144, 1500, 20)[0]
rows.append(("E0 калибровка TTL/usage + задержки", e0, e0, 0, 0))

# E1. Выбор модели: BFCL v4 одношаговые категории (≈1 200 задач, ≈1 200 вх / 100 вых) + свой ru/en IoT-набор
# (440 задач = 220 пар MASSIVE iot, ≈3 000 вх с каталогом MCP / 100 вых, ≈2 вызова на задачу); 6 моделей × 2 повтора.
e1_hi = e1_tin = e1_tout = 0
for m in PRICE:
    for (n, tin, tout) in ((1200, 1200, 100), (440 * 2, 3000, 100)):
        c, ti, to = cost(m, n * 2, tin, tout)
        e1_hi += c; e1_tin += ti; e1_tout += to
rows.append(("E1 выбор модели (BFCL + ru/en IoT), 6 моделей × 2 повтора", e1_hi, e1_hi, e1_tin, e1_tout))

# E2. Простой и фон, 8 ч: OpenClaw-подобный heartbeat 27 000 вх × 16 тиков (A S1, E C3), 3 прогона, gpt-4o-mini;
# свой агент: heartbeat 30 и 29 мин по 2 000 вх × 16 × 3; гейт без событий — 0 вызовов; nanobot/PicoClaw heartbeat ≈ свой.
e2 = 0; t2i = 0
for (n, tin) in ((16 * 3, 27000), (16 * 3 * 2, 2000), (16 * 3 * 2, 4000)):
    c, ti, _ = cost("gpt-4o-mini", n, tin, 20); e2 += c; t2i += ti
c, ti, _ = cost("gpt-5-mini", 16, 27000, 20); e2 += c; t2i += ti   # одна проверка на mini с глубокой скидкой
rows.append(("E2 простой/фон 8 ч (4 агента × режимы × 3 прогона)", e2, e2, t2i, 0))

# E4. T1 — сжатые живые сутки: 6 конфигураций × 2 модели × 10 суток; ≈150 вызовов/сут
# (GAP1 §6.2: 97–166 вызовов/сут для M/M+/H + датчики CASAS + heartbeat), ≈8 000 вх (наивные конфигурации тяжелее,
# оптимизированные легче — среднее, ДОПУЩЕНИЕ), 150 видимых вых.
e4_hi = e4_re = e4_ti = e4_to = 0
for m in ("gpt-4o-mini", "gpt-5-mini"):
    hi, ti, to = cost(m, 6 * 10 * 150, 8000, 150)
    re, _, _ = cost(m, 6 * 10 * 150, 8000, 150, cache_share=0.5)
    e4_hi += hi; e4_re += re; e4_ti += ti; e4_to += to
# + стресс-профиль H/S: 2 конфигурации × 5 суток × 300 вызовов на gpt-4o-mini
hi, ti, to = cost("gpt-4o-mini", 2 * 5 * 300, 8000, 150); re, _, _ = cost("gpt-4o-mini", 2 * 5 * 300, 8000, 150, 0.5)
e4_hi += hi; e4_re += re; e4_ti += ti; e4_to += to
rows.append(("E4 T1 сжатые сутки (6 конф. × 2 модели × 10 сут + стресс)", e4_hi, e4_re, e4_ti, e4_to))

# E5. T2 — реальное время, окно 14–22: 3 конфигурации × 5 прогонов на Pi 5 + 3 на Jetson Nano + 5 суток T1 той же
# трассы для валидации; ≈75 вызовов за 8 ч, 8 000 вх, gpt-4o-mini.
n_runs = 3 * 5 + 3 + 5
hi, ti, to = cost("gpt-4o-mini", n_runs * 75, 8000, 150); re, _, _ = cost("gpt-4o-mini", n_runs * 75, 8000, 150, 0.5)
rows.append(("E5 T2 реальные 8 ч на плате + валидация T1↔T2", hi, re, ti, to))

# E6. Безопасность: режим «правила только в промпте» и «гейт с голым отказом» дополнительно к E4
# (ловушки встроены в трассы E4): 2 режима × 2 модели × 5 суток × 150 вызовов.
e6_hi = e6_re = e6_ti = 0
for m in ("gpt-4o-mini", "gpt-5-mini"):
    hi, ti, to = cost(m, 2 * 5 * 150, 8000, 150); re, _, _ = cost(m, 2 * 5 * 150, 8000, 150, 0.5)
    e6_hi += hi; e6_re += re; e6_ti += ti
rows.append(("E6 безопасность команд (доп. режимы гейта)", e6_hi, e6_re, e6_ti, 0))

# E7. Представление контекста оборудования: 3 представления × k∈{5,20} × 150 задач × 2,5 вызова, ≈7 000 вх, 2 модели.
e7_hi = e7_ti = 0
for m in ("gpt-4.1-nano", "gpt-5-mini"):
    hi, ti, to = cost(m, 3 * 2 * 150 * 2.5, 7000, 100); e7_hi += hi; e7_ti += ti
rows.append(("E7 представление контекста оборудования", e7_hi, e7_hi, e7_ti, 0))

print(f"{'эксперимент':62s} {'верх. ₽':>9s} {'реал. ₽':>9s} {'вход, млн ток.':>15s}")
tot_hi = tot_re = tot_ti = 0
for name, hi, re, ti, to in rows:
    print(f"{name:62s} {hi:9.0f} {re:9.0f} {ti/1e6:15.1f}")
    tot_hi += hi; tot_re += re; tot_ti += ti
print(f"{'ИТОГО ядро':62s} {tot_hi:9.0f} {tot_re:9.0f} {tot_ti/1e6:15.1f}")
print(f"{'ИТОГО с резервом ×1,5 (повторы, отладка, дрейф цен)':62s} {tot_hi*1.5:9.0f} {tot_re*1.5:9.0f}")

# Мощность парного сравнения долей успеха (не меньшая эффективность / TOST, δ = 5 п.п., α = 0,05, мощность 0,8)
z_a, z_b = 1.6449, 1.2816   # z_{0,95}; z_{0,90} (β/2 при истинной разнице 0)
print("\nЧисло парных решений для TOST по доле успеха, δ = 5 п.п.:")
for disc in (0.05, 0.10, 0.15, 0.20):
    n = (z_a + z_b) ** 2 * disc / 0.05 ** 2
    print(f"  доля несогласных пар {disc:.2f}: n ≈ {n:.0f}")
# ДИ отношения медиан ₽/сут по 10 парным суткам: полуширина в логарифме ≈ t_{0,975;9}·s/√10
for s in (0.2, 0.3, 0.5):
    h = 2.262 * s / sqrt(10)
    print(f"  s(log-отношения по суткам)={s}: 95% ДИ отношения ≈ ×/÷ {2.718281828**h:.2f}")
