#!/usr/bin/env python3
"""Бюджет API, мощность и машинное время для MVP-ядра ВКР (THESIS_CONCEPT.md после red team, 06.10.2026).

Это РАСЧЁТ, а не измерение. Цены — каталог RouterAI GET /api/v1/models, 06.10.2026
(снимок F_artifacts/routerai_models_2026-10-06.json). Объёмы, размеры промптов и число вызовов — ДОПУЩЕНИЯ
(помечены в комментариях). «Верх» — без кэша провайдера; «реал.» — 50 % входа из кэша там, где префикс общий.

Запуск: python3 budget_mvp.py > budget_mvp_output_2026-10-06.txt
"""
from math import sqrt, exp

# ₽ за 1M токенов: вход, чтение кэша, выход (RouterAI, 06.10.2026, endpoint `openai`, service_tier default)
PRICE = {
    "gpt-4.1-nano": (11.04, 2.76, 44.16),
    "gpt-5-nano":   (5.52, 0.55, 44.16),
    "gpt-4o-mini":  (16.56, 8.28, 66.25),
    "gpt-5-mini":   (27.60, 2.76, 220.82),
}
REASONING = {"gpt-5-nano": 400, "gpt-5-mini": 400}  # ДОПУЩЕНИЕ: скрытые reasoning-токены на вызов
MAIN = "gpt-4o-mini"  # ДОПУЩЕНИЕ: основная модель до E0-Q; чувствительность к gpt-5-mini — ниже


def cost(model, calls, tin, tout=150, cache=0.0):
    p_in, p_c, p_out = PRICE[model]
    out = tout + REASONING.get(model, 0)
    return calls * (tin * ((1 - cache) * p_in + cache * p_c) + out * p_out) / 1e6


rows = []

# E0-P. Проба провайдера в первый день с ключом: поля usage (cached_tokens в chat и в /generation),
#  судьба prompt_cache_key / prompt_cache_retention, время жизни кэша на паузах 5 / 30 / 120 мин
#  (3 модели × 3 паузы × 3 повтора × 2 вызова, префикс 3 000 токенов), service_tier/flex (20 вызовов),
#  калибровка счётчика токенов T0 по usage.prompt_tokens (30 запросов × 3 модели, 6 000 вх),
#  задержки по часам: 144 коротких запроса × 2 сети на основной модели
p = 0
for m in ("gpt-4o-mini", "gpt-4.1-nano", "gpt-5-mini"):
    p += cost(m, 3 * 3 * 2, 3000, 20) + cost(m, 30, 6000, 20)
p += cost(MAIN, 20, 1500, 20) + cost(MAIN, 2 * 144, 1500, 20)
rows.append(("E0-P", "проба провайдера: поля usage, кэш на паузах, flex, калибровка T0", p, p))

# E0-Q. Выбор основной модели: 440 команд MASSIVE iot (220 ru + 220 en) на инструментах стенда,
#  2 вызова × 3 000 вх; 4 модели + A/A на основной; якорь home-assistant-datasets: 100 задач × 2,5 вызова × 4 000 вх × 2 модели
q = sum(cost(m, 440 * 2, 3000, 100) for m in PRICE) + cost(MAIN, 440 * 2, 3000, 100)
q += cost(MAIN, 100 * 2.5, 4000, 100) + cost("gpt-4.1-nano", 100 * 2.5, 4000, 100)
rows.append(("E0-Q", "выбор модели: MASSIVE iot ru/en 440 × 4 модели + A/A + якорь HA-datasets", q, q))

# E1. Фон 8 ч без реплик на Pi 5. Вызовов за 8 ч и вход на вызов — ДОПУЩЕНИЯ:
#  EdgeCtx-гейт 4 × 6 000; EdgeCtx-hb30 16 × 6 000; PicoClaw как поставляется 16 × 15 000;
#  PicoClaw-best (cron command + MQTT-пуш) 6 × 15 000; nanobot 16 × 15 000 + Dream 4 × 20 000; плата без агента 0
E1 = {
    "idle": 0,
    "edgectx_gate": cost(MAIN, 4, 6000, 50),
    "edgectx_hb30": cost(MAIN, 16, 6000, 50),
    "picoclaw_shipped": cost(MAIN, 16, 15000, 50),
    "picoclaw_best": cost(MAIN, 6, 15000, 50),
    "nanobot": cost(MAIN, 16, 15000, 50) + cost(MAIN, 4, 20000, 200),
}
e1_runs_full = 3 * len(E1)                                   # 6 конфигураций × 3 прогона
e1_runs_mem = 3 * 2 * 2                                      # EdgeCtx-гейт, PicoClaw-best, nanobot × {512, 256} МиБ × 2
e1_runs_4k = 3                                               # те же 3 системы × 1 прогон на ядре со страницами 4 КиБ
e1 = 3 * sum(E1.values())
e1 += 2 * 2 * (E1["edgectx_gate"] + E1["picoclaw_best"] + E1["nanobot"])
e1 += E1["edgectx_gate"] + E1["picoclaw_best"] + E1["nanobot"]
rows.append(("E1", f"фон 8 ч: {e1_runs_full}+{e1_runs_mem}+{e1_runs_4k} прогонов (полная RAM, memory.max, 4K)", e1, e1))

# E2. Контекст оборудования, S-room на sim-mcp. Подтверждающая часть: R1, R2, R4 × k = 20 × основная модель ×
#  320 уникальных задач × 1 повтор × 2,5 вызова × 7 000 вх. Пилот: 50 задач × 3 условия.
#  Разведочная: R1, R4 × k ∈ {5 (3 500 вх), 50 (15 000 вх)} × 160 задач на основной + R1, R4 × k = 20 × 160 на gpt-4.1-nano
conf = cost(MAIN, 3 * 320 * 2.5, 7000, 120)
conf_re = cost(MAIN, 3 * 320 * 2.5, 7000, 120, 0.5)
pilot = cost(MAIN, 3 * 50 * 2.5, 7000, 120)
expl = (cost(MAIN, 2 * 160 * 2.5, 3500, 120) + cost(MAIN, 2 * 160 * 2.5, 15000, 120)
        + cost("gpt-4.1-nano", 2 * 160 * 2.5, 7000, 120))
expl_re = (cost(MAIN, 2 * 160 * 2.5, 3500, 120, 0.5) + cost(MAIN, 2 * 160 * 2.5, 15000, 120, 0.5)
           + cost("gpt-4.1-nano", 2 * 160 * 2.5, 7000, 120, 0.5))
rows.append(("E2", "R1/R2/R4 × k=20 × 320 задач + пилот 50 + разведка k{5,50} и nano", conf + pilot + expl,
             conf_re + pilot + expl_re))

# E3-live. Контроль качества политик истории: 300 контрольных вопросов (30 сгенерированных суток × 10) ×
#  3 политики EdgeCtx (полная / маскирование+окно / сводка в system prompt); контекст на вопрос — ДОПУЩЕНИЕ:
#  30 000 / 10 000 / 6 000 токенов; + внешняя точка PicoClaw seahorse, 300 × 10 000
e3 = cost(MAIN, 300, 30000, 60) + cost(MAIN, 300, 10000, 60) + cost(MAIN, 300, 6000, 60) + cost(MAIN, 300, 10000, 60)
e3_re = (cost(MAIN, 300, 30000, 60, 0.5) + cost(MAIN, 300, 10000, 60, 0.5) + cost(MAIN, 300, 6000, 60, 0.5)
         + cost(MAIN, 300, 10000, 60, 0.5))
rows.append(("E3-live", "контрольные вопросы: 300 × 3 политики + seahorse PicoClaw", e3, e3_re))

rows.append(("E3/E4-T0", "факторные планы истории и пробуждения на виртуальных часах (оракул)", 0, 0))

# E5-T2. Рабочий день 14–22 на Pi 5, M+: 5 трасс-блоков × 3 системы. Вызовов за окно — ДОПУЩЕНИЕ:
#  реплики ≈5 команд × 2,9 ≈ 15 вызовов у всех; фон: B0-hb 16 тиков, итог ≈4 пробуждения, PicoClaw-best ≈6;
#  вход на вызов: B0-hb 8 000, итог 6 000, PicoClaw-best 15 000
t2 = 5 * (cost(MAIN, 31, 8000) + cost(MAIN, 19, 6000) + cost(MAIN, 21, 15000))
t2_re = 5 * (cost(MAIN, 31, 8000, cache=0.5) + cost(MAIN, 19, 6000, cache=0.5) + cost(MAIN, 21, 15000, cache=0.5))
rows.append(("E5-T2", "рабочий день: 5 трасс × {B0-hb, итог, PicoClaw-best}", t2, t2_re))

# E6. Камера на Pi 5 с YOLO26n (NCNN) на борту: {кадр в LLM, локальная сводка, кадр по запросу} × 150 вопросов × 1;
#  ДОПУЩЕНИЕ: кадр (detail=low у gpt-4o-mini — 2 833 ток. по OpenAI vision guide) + 2 500 контекста;
#  сводка 60 + 2 500; по запросу — 2 вызова (сводка, затем кадр в 40 % вопросов)
e6 = (cost(MAIN, 150, 2833 + 2500) + cost(MAIN, 150, 2560)
      + cost(MAIN, 150, 2560) + cost(MAIN, 0.4 * 150, 2833 + 2500))
rows.append(("E6", "камера: кадр / сводка детектора / кадр по запросу", e6, e6))

ext = []
ext.append(("X-T1", "TTL-aware ускоренный день (только если E0-P подтвердит cached_tokens и TTL в минутах)",
            cost(MAIN, 3 * 10 * 120, 7000), cost(MAIN, 3 * 10 * 120, 7000, cache=0.5)))
ext.append(("X-net", "трафик клиента: поток/без, keep-alive, TLS (3 000 коротких вызовов gpt-4.1-nano)",
            cost("gpt-4.1-nano", 3000, 1000, 100), cost("gpt-4.1-nano", 3000, 1000, 100)))
ext.append(("X-robot", "записанное демо S-robot в Gazebo: 1 день × 150 вызовов × 9 000",
            cost(MAIN, 150, 9000), cost(MAIN, 150, 9000, cache=0.5)))
ext.append(("X-oc", "OpenClaw на Pi 5: фон 3 × 8 ч + 3 прогона T2 (≈28 тыс. вх на вызов)",
            cost(MAIN, 3 * 16 + 3 * 75, 28000), cost(MAIN, 3 * 16 + 3 * 75, 28000, cache=0.5)))
ext.append(("X-E2", "подтверждающая часть E2 на gpt-5-mini + второй повтор на основной модели",
            cost("gpt-5-mini", 3 * 320 * 2.5, 7000, 120) + cost(MAIN, 3 * 320 * 2.5, 7000, 120),
            cost("gpt-5-mini", 3 * 320 * 2.5, 7000, 120, 0.5) + cost(MAIN, 3 * 320 * 2.5, 7000, 120, 0.5)))

print("БЮДЖЕТ API MVP-ядра (₽, цены RouterAI 06.10.2026; расчёт, не измерение)")
print(f"{'код':9s} {'что':82s} {'верх':>6s} {'реал.':>6s}")
th = tr = 0
for code, name, hi, re in rows:
    print(f"{code:9s} {name:82s} {hi:6.0f} {re:6.0f}")
    th += hi; tr += re
print(f"{'ЯДРО':9s} {'итого':82s} {th:6.0f} {tr:6.0f}")
print(f"{'':9s} {'с резервом ×1,5':82s} {th*1.5:6.0f} {tr*1.5:6.0f}")
for code, name, hi, re in ext:
    print(f"{code:9s} {name:82s} {hi:6.0f} {re:6.0f}")

# Чувствительность: основная модель gpt-5-mini вместо gpt-4o-mini во всех статьях, где стоит MAIN
MAIN_ALT = "gpt-5-mini"
ratio_hi = (cost(MAIN_ALT, 1, 7000, 120) / cost(MAIN, 1, 7000, 120))
print(f"\nЧувствительность: вызов 7 000/120 на gpt-5-mini дороже, чем на gpt-4o-mini, в {ratio_hi:.2f} раза (верх); "
      f"ядро тогда ≈ {th*ratio_hi:.0f} ₽ (верх, грубо)")

# Мощность E2 и E3-live: не меньшая эффективность по доле успеха, δ = 5 п.п., мощность 0,8 при нулевой разнице,
# поправка Холма на 2 подтверждающих сравнения → первое на α = 0,025 (односторонний)
z = {"0.05": 1.6449, "0.025": 1.9600, "0.00417": 2.6383}
zb = 0.8416       # мощность 0,8, односторонний тест не меньшей эффективности
zb2 = 1.2816      # z_{1-β/2}: двусторонний TOST эквивалентности (так считал red team)
d = 0.05
print("\nМОЩНОСТЬ (парные решения, δ = 5 п.п.)")
print(" доля несогл. | NI, α=0,05 | NI, Холм по 2 (α=0,025) | TOST, α=0,05 | TOST, Холм по 12")
for pd in (0.05, 0.08, 0.10, 0.13, 0.15):
    print(f"   {pd:.2f}       | {(z['0.05']+zb)**2*pd/d**2:9.0f} | {(z['0.025']+zb)**2*pd/d**2:23.0f} | "
          f"{(z['0.05']+zb2)**2*pd/d**2:12.0f} | {(z['0.00417']+zb2)**2*pd/d**2:16.0f}")
for n in (300, 320, 400):
    print(f" n = {n}: NI с Холмом по 2 выдерживает долю несогласных пар до {n*d**2/(z['0.025']+zb)**2:.3f}")

# T2: 5 трасс-блоков, каждая трасса проиграна на всех системах → парный анализ по трассе
print("\nT2: 95 % ДИ отношения (×/÷) по 5 блокам")
for s in (0.2, 0.3, 0.5):
    paired = exp(2.776 * s / sqrt(5))
    print(f"  s(log-отношения внутри трассы) = {s}: парно ×/÷{paired:.2f}; "
          f"непарно (симуляция red team boot5.py) ×/÷{ {0.2: 1.38, 0.3: 1.63, 0.5: 2.28}[s]:.2f}")

# Машинное время платы
e1_runs = e1_runs_full + e1_runs_mem + e1_runs_4k
print("\nМАШИННОЕ ВРЕМЯ ПЛАТЫ (Pi 5)")
print(f"  E1: {e1_runs} прогонов × 8 ч = {e1_runs*8} ч ≈ {e1_runs/3:.0f} суток платы (3 прогона в сутки; реплик нет, окно не важно)")
print(f"  E5-T2: 5 трасс × 3 системы = 15 прогонов в окне 14–22 = 15 суток платы")
print(f"  E6: ≈3 суток; итого ≈ {e1_runs/3 + 15 + 3:.0f} суток платы против 59 суток февраля–марта 2027")
