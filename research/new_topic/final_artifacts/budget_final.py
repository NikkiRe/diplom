#!/usr/bin/env python3
"""Бюджет API и расчёт мощности для ИТОГОВОЙ концепции ВКР (THESIS_CONCEPT.md).

Это РАСЧЁТ, а не измерение. Цены: публичный каталог RouterAI GET https://routerai.ru/api/v1/models,
перепроверен 06.10.2026 (совпадает со снимком F_artifacts/routerai_models_2026-10-06.json).
Объёмы экспериментов, размеры промптов и число вызовов — ДОПУЩЕНИЯ концепции (помечены в комментариях).
«Верх» — без кэша провайдера; «реал.» — 50 % входа из кэша (GAP1 §6.2: в сценариях с датчиками 50–72 %).

Запуск: python3 budget_final.py > budget_final_output_2026-10-06.txt
"""
from math import sqrt, log, exp, ceil

# ₽ за 1M токенов: вход, чтение кэша, выход (RouterAI, 06.10.2026)
PRICE = {
    "gpt-4.1-nano": (11.04, 2.76, 44.16),
    "gpt-5-nano":   (5.52, 0.55, 44.16),
    "gpt-4o-mini":  (16.56, 8.28, 66.25),
    "gpt-5-mini":   (27.60, 2.76, 220.82),
}
# ДОПУЩЕНИЕ: скрытые reasoning-токены на вызов у gpt-5-* (тарифицируются как выход); проверяется в E0
REASONING = {"gpt-5-nano": 400, "gpt-5-mini": 400}


def cost(model, calls, tin, tout=150, cache=0.0):
    p_in, p_c, p_out = PRICE[model]
    out = tout + REASONING.get(model, 0)
    return calls * (tin * ((1 - cache) * p_in + cache * p_c) + out * p_out) / 1e6


rows = []  # (код, описание, верх, реал., ядро?)

# E0. Провайдер и модели
#  C: калибровка TTL кэша (ttl_probe.py из GAP1, ₽ на провайдера из ttl_probe_plan_stdout.txt:
#     gpt-4o-mini 6,09; gpt-5-mini 8,98; gpt-4.1-nano ≈4 — ДОПУЩЕНИЕ по аналогии) × {OpenAI, Azure} × 3 повтора в разные часы
c = (6.09 + 8.98 + 4.0) * 2 * 3
#  наблюдаемость полей usage + задержки по часам: 4 модели × 144 коротких запроса (раз в 10 мин) × 2 сети (ИТМО, мобильная)
for m in PRICE:
    c += 2 * cost(m, 144, 1500, 20)
#  проба rate limit / overflow-маршрутизации: 300 коротких вызовов gpt-4.1-nano
c += cost("gpt-4.1-nano", 300, 1500, 20)
rows.append(("E0-C", "калибровка TTL кэша, поля usage, задержки, rate limit", c, c, True))
#  Q: выбор модели по cost-of-pass: BFCL-подмножество 300 задач (1 200 вх / 100 вых, 1,3 вызова)
#     + 440 команд MASSIVE iot (220 ru + 220 en) на MCP-инструментах стенда (3 000 вх / 100 вых, 2 вызова); 4 модели;
#     + A/A-повтор на основной модели (gpt-4o-mini в расчёте)
q = 0
for m in PRICE:
    q += cost(m, 300 * 1.3, 1200, 100) + cost(m, 440 * 2, 3000, 100)
q += cost("gpt-4o-mini", 300 * 1.3, 1200, 100) + cost("gpt-4o-mini", 440 * 2, 3000, 100)
rows.append(("E0-Q", "выбор модели: BFCL 300 + MASSIVE iot ru/en 440, 4 модели + A/A", q, q, True))

# E1. Фон без пользователя, 8 ч, одинаковая непустая задача наблюдения:
#  6 конфигураций (плата без агента; свой-гейт; свой-heartbeat 30; PicoClaw как есть; PicoClaw с патчем паритета; nanobot)
#  × 5 прогонов на основной плате + 3 конфигурации × 3 прогона на второй; heartbeat 30 мин = 16 тиков за 8 ч;
#  ДОПУЩЕНИЕ: 6 000 вх (свой) / 15 000 вх (PicoClaw, nanobot) на тик; гейт будит LLM ≈4 раза за 8 ч по значимым событиям
e1 = 0
e1 += 5 * (cost("gpt-4o-mini", 4, 6000, 50) + cost("gpt-4o-mini", 16, 6000, 50)
           + 2 * cost("gpt-4o-mini", 16, 15000, 50) + cost("gpt-4o-mini", 16, 15000, 50))
e1 += 3 * (cost("gpt-4o-mini", 4, 6000, 50) + cost("gpt-4o-mini", 16, 6000, 50) + cost("gpt-4o-mini", 16, 15000, 50))
rows.append(("E1", "фон 8 ч без пользователя (2 платы)", e1, e1, True))

# E2. Контекст оборудования (S-room): 4 представления × k∈{5,20} × 2 модели × 160 задач × 2 повтора × 2,5 вызова;
#  ДОПУЩЕНИЕ: 7 000 вх в среднем (k=5 ≈ 3–4 тыс., k=20 со снимком ≈ 10 тыс.; GAP2 §6: каталог 9 782 / 2 861 ток.)
calls_e2 = 4 * 2 * 160 * 2 * 2.5
e2_hi = cost("gpt-4o-mini", calls_e2, 7000, 120) + cost("gpt-4.1-nano", calls_e2, 7000, 120)
e2_re = cost("gpt-4o-mini", calls_e2, 7000, 120, 0.5) + cost("gpt-4.1-nano", calls_e2, 7000, 120, 0.5)
rows.append(("E2", "контекст оборудования: 4 предст. × k{5,20} × 2 модели × 160 × 2", e2_hi, e2_re, True))

# E3/E4 в режиме T0 (виртуальные часы, оракул-LLM, токены o200k офлайн, ₽ по кривой p(a)) — 0 ₽
rows.append(("E3/E4-T0", "полные факторные планы истории и пробуждения LLM (офлайн)", 0, 0, True))

# E5-T1. «Лестница» на сжатых живых сутках (TTL-aware), профиль M+ + датчики CASAS + ловушки, 10 парных суток:
#  6 конфигураций (B0 наивный → +гейт → +раскладка → +окно истории → +pull = итог; B5) на основной модели;
#  ДОПУЩЕНИЕ: 120 вызовов/сут × 7 000 вх в среднем (GAP1 §6.2: 97–166 вызовов/сут у наивного)
t1 = 6 * 10 * 120
e5a_hi = cost("gpt-4o-mini", t1, 7000)
e5a_re = cost("gpt-4o-mini", t1, 7000, cache=0.5)
#  + вторая модель с глубокой скидкой за кэш (0,1×) для B0 и итоговой: 2 × 10 суток
e5a_hi += cost("gpt-5-mini", 2 * 10 * 120, 7000)
e5a_re += cost("gpt-5-mini", 2 * 10 * 120, 7000, cache=0.5)
rows.append(("E5-T1", "лестница механизмов: 6 конф. × 10 сут (+2 конф. на gpt-5-mini)", e5a_hi, e5a_re, True))

# E5-T2. Реальное время 14–22 на основной плате: B0, итог, PicoClaw (как есть), PicoClaw (паритет), nanobot × 5 прогонов;
#  на второй плате итог × 3; ДОПУЩЕНИЕ: 75 вызовов за 8 ч × 8 000 вх
runs = 5 * 5 + 3
e5b_hi = cost("gpt-4o-mini", runs * 75, 8000)
e5b_re = cost("gpt-4o-mini", runs * 75, 8000, cache=0.5)
#  валидация T1↔T2: 5 пар суток T1 с управлением по записанным ответам на тех же трассах
e5b_hi += cost("gpt-4o-mini", 5 * 75, 8000)
e5b_re += cost("gpt-4o-mini", 5 * 75, 8000, cache=0.5)
rows.append(("E5-T2", "рабочий день 8 ч на платах + валидация T1/T2", e5b_hi, e5b_re, True))

# E5-net. Сетевой подэксперимент: 3 000 коротких вызовов gpt-4.1-nano (1 000 вх / 100 вых), остальное на mock-llm
net = cost("gpt-4.1-nano", 3000, 1000, 100)
rows.append(("E5-net", "трафик клиента LLM: поток/без, keep-alive, TLS-возобновление", net, net, True))

# E6. Камера: {кадр в LLM, локальная сводка, кадр по запросу (resource_link)} × 150 вопросов × 2 повтора, gpt-4o-mini;
#  ДОПУЩЕНИЕ: кадр ≈3 000 токенов изображения + 2 500 контекста; сводка ≈300 + 2 500; по запросу ≈1 500 + 2 500 в среднем
e6 = 2 * (cost("gpt-4o-mini", 150, 5500) + cost("gpt-4o-mini", 150, 2800) + cost("gpt-4o-mini", 150, 4000))
rows.append(("E6", "камера: кадр / локальная сводка / по запросу", e6, e6, True))

# Расширения (только после ядра)
ext = []
ext.append(("X1", "S-robot: день T1 в Gazebo/TurtleBot3 (2 конф. × 2 сут)",
            cost("gpt-4o-mini", 2 * 2 * 150, 9000), cost("gpt-4o-mini", 2 * 2 * 150, 9000, cache=0.5)))
ext.append(("X2", "OpenClaw на Pi 5: фон 3 × 8 ч + 3 прогона T2 (≈28 тыс. вх на вызов)",
            cost("gpt-4o-mini", 3 * 16 + 3 * 75, 28000), cost("gpt-4o-mini", 3 * 16 + 3 * 75, 28000, cache=0.5)))
ext.append(("X3", "E2: третий повтор и третья модель (gpt-5-mini)",
            cost("gpt-4o-mini", calls_e2 / 2, 7000, 120) + cost("gpt-4.1-nano", calls_e2 / 2, 7000, 120)
            + cost("gpt-5-mini", calls_e2 * 1.5, 7000, 120),
            cost("gpt-4o-mini", calls_e2 / 2, 7000, 120, 0.5) + cost("gpt-4.1-nano", calls_e2 / 2, 7000, 120, 0.5)
            + cost("gpt-5-mini", calls_e2 * 1.5, 7000, 120, 0.5)))

print("БЮДЖЕТ API (₽, цены RouterAI 06.10.2026; расчёт, не измерение)")
print(f"{'код':9s} {'что':66s} {'верх':>7s} {'реал.':>7s}")
th = tr = 0
for code, name, hi, re, _ in rows:
    print(f"{code:9s} {name:66s} {hi:7.0f} {re:7.0f}")
    th += hi; tr += re
print(f"{'ЯДРО':9s} {'итого':66s} {th:7.0f} {tr:7.0f}")
print(f"{'':9s} {'с резервом ×1,5 (отладка, повторы, дрейф цен)':66s} {th*1.5:7.0f} {tr*1.5:7.0f}")
xh = xr = 0
for code, name, hi, re in ext:
    print(f"{code:9s} {name:66s} {hi:7.0f} {re:7.0f}")
    xh += hi; xr += re
print(f"{'РАСШ.':9s} {'итого расширений':66s} {xh:7.0f} {xr:7.0f}")

# Мощность: парный TOST/не меньшая эффективность по доле успеха, δ = 5 п.п., α = 0,05, мощность 0,8 при нулевой разнице
z_a, z_b = 1.6449, 1.2816
print("\nМОЩНОСТЬ. Парные решения для TOST по доле успеха (δ = 5 п.п.):")
for disc in (0.05, 0.08, 0.10, 0.13, 0.15, 0.20):
    print(f"  доля несогласных пар {disc:.2f}: n ≈ {(z_a + z_b) ** 2 * disc / 0.05 ** 2:.0f}")
for n in (320, 480, 600):
    print(f"  n = {n}: хватает при доле несогласных пар до ≈ {n * 0.05 ** 2 / (z_a + z_b) ** 2:.3f} "
          f"(номинально; повторы одной задачи коррелированы → ДИ кластерным бутстрепом по задачам)")

# ₽/сут по 10 парным суткам: полуширина 95 % ДИ log-отношения ≈ t_{0,975;9}·s/√10
print("\nДИ отношения медиан ₽/сут по 10 парным суткам:")
for s in (0.2, 0.3, 0.5):
    print(f"  s = {s}: ×/÷ {exp(2.262 * s / sqrt(10)):.2f}")

# Валидация T1↔T2: TOST на среднем log(₽_T1/₽_T2), граница ±ln(1,05), α = 0,05, мощность 0,8 при нулевой разнице
T = {4: (2.132, 1.533), 5: (2.015, 1.476), 7: (1.895, 1.415), 9: (1.833, 1.383), 14: (1.761, 1.345), 19: (1.729, 1.330),
     29: (1.699, 1.311)}  # df: (t_{0,95}, t_{0,90}) — таблица t-распределения
m = log(1.05)
print("\nВалидация T1/T2 (граница ±5 %): нужное число пар при стандартном отклонении s log-отношения:")
for s in (0.02, 0.03, 0.04, 0.06, 0.08):
    need = None
    for df in sorted(T):
        ta, tb = T[df]
        if (ta + tb) * s / sqrt(df + 1) <= m:
            need = df + 1
            break
    print(f"  s = {s:.2f}: n ≥ {need if need else '>30'}")

# Пересчёт ₽ в год и на парк (модель GAP1 §6.2, gpt-4o-mini, не измерение)
print("\nМасштаб (модель GAP1 §6.2, gpt-4o-mini): «M + датчики + heartbeat» 6,46 ₽/сут против «только пользователь» 1,38 ₽/сут")
for rub in (6.46, 1.38):
    print(f"  {rub:5.2f} ₽/сут → {rub*365:7.0f} ₽/год на устройство → {rub*365*100/1000:6.0f} тыс. ₽/год на парк из 100 устройств")

# Чувствительность: основная модель gpt-5-mini вместо gpt-4o-mini в E2 и в 6 конфигурациях лестницы E5-T1
# (вторая модель лестницы для B0 и итога остаётся gpt-5-mini — верхняя оценка)
d_hi = (cost("gpt-5-mini", calls_e2, 7000, 120) - cost("gpt-4o-mini", calls_e2, 7000, 120)) \
     + (cost("gpt-5-mini", t1, 7000) - cost("gpt-4o-mini", t1, 7000))
d_re = (cost("gpt-5-mini", calls_e2, 7000, 120, 0.5) - cost("gpt-4o-mini", calls_e2, 7000, 120, 0.5)) \
     + (cost("gpt-5-mini", t1, 7000, cache=0.5) - cost("gpt-4o-mini", t1, 7000, cache=0.5))
print(f"\nЧувствительность: основная модель gpt-5-mini (E2 и лестница E5-T1): ядро ≈ {th + d_hi:.0f} ₽ (верх) / "
      f"{tr + d_re:.0f} ₽ (реал.) без резерва; прирост {d_hi:.0f} / {d_re:.0f} ₽")
